const goldenInventoryPath = "testdata/inventory.md"

// TestInventoryMatchesGolden is the clause the other lint clauses cannot cover.
//
// Derivation is self-maintaining by design, which is also its blind spot: a new
// RPC annotated with a permission that is already classified resolves silently
// and joins whichever sets hold it — no clause over the tables can see that,
// because no table changed. The golden file turns every such method into a
// reviewable line in the diff, so adding an RPC that lands in a preset is a
// decision somebody signs rather than a side effect.
//
// Regenerate after any RPC or table change:
//
//	AI_ACCESS_INVENTORY=write go test ./backend/api/aiaccess/ -run TestInventoryMatchesGolden
func TestInventoryMatchesGolden(t *testing.T) {
	got, err := renderInventory()
	require.NoError(t, err)

	if os.Getenv("AI_ACCESS_INVENTORY") == "write" {
		require.NoError(t, os.WriteFile(goldenInventoryPath, []byte(got), 0o600))
		return
	}

	want, err := os.ReadFile(goldenInventoryPath)
	require.NoError(t, err)
	require.Equal(t, string(want), got,
		"the resolved capability of at least one RPC changed. Review the diff — a method moving into or out of a preset is a policy change — then regenerate with AI_ACCESS_INVENTORY=write go test ./backend/api/aiaccess/ -run TestInventoryMatchesGolden")
}

// renderInventory returns the published inventory: every v1 RPC with the
// capability it requires and the presets that admit it, plus the sets and
// classes themselves.
func renderInventory() (string, error) {
	var b strings.Builder
	counts := map[string]int{}

	b.WriteString("# AI access inventory\n\n")
	b.WriteString("Generated by `AI_ACCESS_INVENTORY=write go test ./backend/api/aiaccess/ -run TestInventoryMatchesGolden`. Do not edit by hand.\n\n")
	b.WriteString("| Method | Requires | Resolution | Read-only | Read-write |\n|---|---|---|---|---|\n")

	for _, procedure := range V1Procedures() {
		requirement, err := Required(procedure, nil)
		if err != nil {
			return "", err
		}

		resolution := "annotation"
		if _, ok := explicitMethods[procedure]; ok {
			resolution = "explicit"
		}
		requires, readOnly, readWrite := "FORBIDDEN", "", ""
		if requirement.Forbidden {
			resolution = "forbidden"
		} else {
			parts := make([]string, 0, len(requirement.Capabilities))
			for _, capability := range requirement.Capabilities {
				parts = append(parts, string(capability))
			}
			requires = strings.Join(parts, " + ")
			if ReadOnly.Allows(requirement) {
				readOnly, counts["read-only"] = "yes", counts["read-only"]+1
			}
			if ReadWrite.Allows(requirement) {
				readWrite, counts["read-write"] = "yes", counts["read-write"]+1
			}
		}
		counts[resolution]++
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s |\n",
			strings.TrimPrefix(procedure, "/bytebase.v1."), requires, resolution, readOnly, readWrite)
	}

	universe, err := Universe()
	if err != nil {
		return "", err
	}
	fmt.Fprintf(&b, "\n## Counts\n\nMethods: %d (annotation %d, explicit %d, forbidden %d). Admitted: read-only %d, read-write %d.\n",
		len(V1Procedures()), counts["annotation"], counts["explicit"], counts["forbidden"], counts["read-only"], counts["read-write"])
	fmt.Fprintf(&b, "Capabilities: universe %d = read-write %d + administration %d + approval %d; read-only %d; minted operation IDs %d.\n",
		len(universe), len(ReadWrite.Capabilities()), len(adminCapabilities), len(approvalCapabilities), len(ReadOnly.Capabilities()), len(operations))

	writeCapabilities(&b, "Read-only set", ReadOnly.Capabilities())
	writeCapabilities(&b, "Read-write set", ReadWrite.Capabilities())
	writeCapabilities(&b, "Administration class (in no set)", adminCapabilities)
	writeCapabilities(&b, "Approval class (in no set)", approvalCapabilities)

	fmt.Fprintf(&b, "\n## Forbidden methods (%d)\n\n", len(forbiddenMethods))
	for _, procedure := range V1Procedures() {
		if reason, ok := forbiddenMethods[procedure]; ok {
			fmt.Fprintf(&b, "- `%s` — %s\n", strings.TrimPrefix(procedure, "/bytebase.v1."), reason)
		}
	}
	return b.String(), nil
}

func writeCapabilities(b *strings.Builder, title string, capabilities []Capability) {
	fmt.Fprintf(b, "\n## %s (%d)\n\n", title, len(capabilities))
	for _, capability := range capabilities {
		fmt.Fprintf(b, "- `%s`\n", capability)
	}
}

// TestInventoryCoversEveryRegisteredMethod keeps the registry walk honest: the
// count is not hardcoded, but the services are, so a service that stops being
// registered (or a proto package rename) is loud rather than silent.
func TestInventoryCoversEveryRegisteredMethod(t *testing.T) {
	procedures := V1Procedures()
	require.NotEmpty(t, procedures)

	services := map[string]bool{}
	for _, procedure := range procedures {
		parts := strings.Split(procedure, "/")
		require.Len(t, parts, 3, "procedure %q", procedure)
		services[parts[1]] = true

		// Every procedure the walk yields must be resolvable by the ACL's own
		// descriptor reader; that is what makes them the same universe.
		_, err := auth.GetAuthContext(procedure)
		require.NoError(t, err)
	}
	for _, service := range []string{
		"bytebase.v1.AuthService",
		"bytebase.v1.DatabaseService",
		"bytebase.v1.InstanceService",
		"bytebase.v1.IssueService",
		"bytebase.v1.PlanService",
		"bytebase.v1.RolloutService",
		"bytebase.v1.SQLService",
		"bytebase.v1.WorksheetService",
	} {
		require.True(t, services[service], "service %q missing from the registry walk", service)
	}
}
