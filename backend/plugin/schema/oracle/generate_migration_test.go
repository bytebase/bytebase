// TestGenerateMigration runs the rollback generator over metadata Oracle itself
// reported for each fixture: diff the post-migration schema back to the initial
// one and compare the DDL against the recorded golden. The metadata comes from
// testdata/generate_migration/*.json, captured by TestGenerateMigrationAgainstOracle.
//
// Set record to regenerate the .sql goldens; it needs no Oracle. Refreshing the
// .json metadata does, and is TestGenerateMigrationAgainstOracle's job.
func TestGenerateMigration(t *testing.T) {
	t.Parallel()

	const record = false

	for _, tc := range generateMigrationCases() {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			schemaA, schemaB := loadGenerateMigrationFixture(t, tc.name)

			dbSchemaA := model.NewDatabaseMetadata(schemaA, nil, nil, storepb.Engine_ORACLE, false)
			dbSchemaB := model.NewDatabaseMetadata(schemaB, nil, nil, storepb.Engine_ORACLE, false)

			// Diff B back to A: the migration under test is the rollback.
			diff, err := schema.GetDatabaseSchemaDiff(storepb.Engine_ORACLE, dbSchemaB, dbSchemaA)
			require.NoError(t, err, "failed to diff %s", tc.description)

			rollbackDDL, err := schema.GenerateMigration(storepb.Engine_ORACLE, diff)
			require.NoError(t, err, "failed to generate migration for %s", tc.description)

			goldenPath := generateMigrationGoldenPath(tc.name)
			if record {
				require.NoError(t, os.WriteFile(goldenPath, []byte(rollbackDDL), 0o644))
				return
			}

			want, err := os.ReadFile(goldenPath)
			require.NoErrorf(t, err, "missing golden %s; set record to regenerate", goldenPath)
			require.Equal(t, string(want), rollbackDDL, "generated migration changed for %s", tc.description)
		})
	}
}

const generateMigrationFixtureDir = "testdata/generate_migration"

// generateMigrationFixture is one case's pair of engine-reported schemas: the
// state after initialSchema, and the state after migrationDDL. Both are
// protojson because storepb messages do not round-trip through encoding/json.
type generateMigrationFixture struct {
	SchemaA json.RawMessage `json:"schemaA"`
	SchemaB json.RawMessage `json:"schemaB"`
}

func generateMigrationFixturePath(name string) string {
	return filepath.Join(generateMigrationFixtureDir, name+".json")
}

func generateMigrationGoldenPath(name string) string {
	return filepath.Join(generateMigrationFixtureDir, name+".sql")
}

// loadGenerateMigrationFixture reads the metadata Oracle reported for a case.
func loadGenerateMigrationFixture(t *testing.T, name string) (*storepb.DatabaseSchemaMetadata, *storepb.DatabaseSchemaMetadata) {
	t.Helper()

	path := generateMigrationFixturePath(name)
	raw, err := os.ReadFile(path)
	require.NoErrorf(t, err, "missing fixture %s; regenerate by setting record = true in TestGenerateMigrationAgainstOracle, then running: go test -run TestGenerateMigrationAgainstOracle ./backend/plugin/schema/oracle/", path)

	var fixture generateMigrationFixture
	require.NoError(t, json.Unmarshal(raw, &fixture), "failed to read %s", path)

	schemaA := &storepb.DatabaseSchemaMetadata{}
	require.NoError(t, common.ProtojsonUnmarshaler.Unmarshal(fixture.SchemaA, schemaA), "failed to decode schemaA in %s", path)
	schemaB := &storepb.DatabaseSchemaMetadata{}
	require.NoError(t, common.ProtojsonUnmarshaler.Unmarshal(fixture.SchemaB, schemaB), "failed to decode schemaB in %s", path)

	return schemaA, schemaB
}

